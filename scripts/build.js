'use strict';

var fs = require('fs');
var path = require('path');

var root = path.resolve(__dirname, '..');
var modules = [
  'src/styles.js',
  'src/api.js',
  'src/filters.js',
  'src/catalog.js',
  'src/plugin.js'
];
var output = path.join(root, 'lampa', 'russian-cinema.js');
var bundle = '/* Generated by npm run build. Edit the modules in src/ instead. */\n';

modules.forEach(function (file) {
  bundle += '\n/* ' + file + ' */\n' + fs.readFileSync(path.join(root, file), 'utf8').trim() + '\n';
});

fs.writeFileSync(output, bundle, 'utf8');
process.stdout.write('Built ' + path.relative(root, output) + ' from ' + modules.length + ' modules.\n');
